def cross_check_against_core() -> str:
    """Agree with `ed448-goldilocks-plus` through the gated core, if present.

    One exact RFC vector proves the algorithm; agreeing with a completely
    separate implementation over random seeds proves it did not get lucky.
    Needs the test-only build (SPEC_GROUP.md §15.1) because production has no
    way to fix a signing key -- returns a reason string when it cannot run.
    """
    try:
        import otrv4_core
    except ImportError:
        return "otrv4_core is not installed"
    if not hasattr(otrv4_core.Ed448KeyHandle, "from_seed_bytes"):
        return ("the installed core is a production build: no from_seed_bytes "
                "(this is the correct state for a release; rebuild with "
                "OTRV4PLUS_ALLOW_TEST_GATES=1 --features test-only-kdf to "
                "cross-check)")
    for index in range(8):
        seed = bytes((index * 37 + position) % 256 for position in range(57))
        message = b"cross-check message %d" % index
        handle = otrv4_core.Ed448KeyHandle.from_seed_bytes(seed)
        if bytes(handle.public_bytes()) != public_key(seed):
            raise AssertionError(
                "public key disagreement with otrv4_core at seed %d" % index)
        theirs = bytes(handle.sign(message))
        ours = sign(seed, message)
        if theirs != ours:
            raise AssertionError(
                "signature disagreement with otrv4_core at seed %d\n"
                "  core: %s\n  rfc : %s" % (index, theirs.hex(), ours.hex()))
        if not verify(public_key(seed), message, theirs):
            raise AssertionError("core signature failed RFC 8032 verification")
    return ""


def _self_check() -> None:
    for vector in RFC_8032_VECTORS:
        seed = bytes.fromhex(vector["seed"])
        message = bytes.fromhex(vector.get("message", ""))
        expected_pub = bytes.fromhex(vector["public"])
        got_pub = public_key(seed)
        assert got_pub == expected_pub, (
            "%s: public key mismatch\n  got %s\n  want %s"
            % (vector["name"], got_pub.hex(), expected_pub.hex()))
        if "signature" not in vector:
            print("RFC 8032 §7.4 %-8s ok (public key only)" % vector["name"])
            continue
        expected_sig = bytes.fromhex(vector["signature"])
        got_sig = sign(seed, message)
        assert got_sig == expected_sig, (
            "%s: signature mismatch\n  got %s\n  want %s"
            % (vector["name"], got_sig.hex(), expected_sig.hex()))
        assert verify(expected_pub, message, expected_sig)
        assert not verify(expected_pub, message + b"\x00", expected_sig)
        print("RFC 8032 §7.4 %-8s ok" % vector["name"])


if __name__ == "__main__":
    _self_check()
    skipped = cross_check_against_core()
    if skipped:
        print("cross-check against otrv4_core skipped: %s" % skipped)
    else:
        print("cross-check against otrv4_core (ed448-goldilocks-plus): ok")
    print("all RFC 8032 Ed448 self-checks passed")
