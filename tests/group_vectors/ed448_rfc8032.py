#!/usr/bin/env python3
"""Ed448 (RFC 8032) in pure Python, for generating protocol test vectors.

WHY THIS FILE EXISTS
====================
Test vectors produced by the implementation they are meant to check prove only
that the implementation agrees with itself.  That is the exact defect
GROUP_CRYPTO_AUDIT.md §2 found in the old ML-KEM tests, and SPEC_GROUP.md §15.2
forbids repeating it.

So the group vectors are generated by an encoder written from SPEC_GROUP.md,
and the signatures in them are produced by *this* file: a transcription of the
RFC 8032 reference algorithm that shares no code with `otrv4_core`, with
`ed448-goldilocks-plus`, or with anything else in this repository.

It is deliberately naive -- affine coordinates, a modular inverse per point
addition.  A few hundred signatures take a few seconds, which is all that is
ever asked of it.

NOT FOR PRODUCTION USE
======================
This is variable-time arithmetic on secret scalars.  It leaks through timing
and must never be imported by client code.  Nothing outside
`tests/group_vectors/` may import it; `tests/test_group_vectors.py` enforces
that.  Production signing is `Ed448KeyHandle.sign()`, where the key is
Rust-owned and never becomes a Python object.

Self-check: `python3 ed448_rfc8032.py` verifies the RFC 8032 §7.4 vectors.
"""

import hashlib

# ---------------------------------------------------------------- parameters
# RFC 8032 §5.2.  edwards448: x^2 + y^2 = 1 + d x^2 y^2 over GF(p).
P = 2**448 - 2**224 - 1
D = -39081 % P
L = (2**446
     - 13818066809895115352007386748515426880336692474882178609894547503885)
B_X = int("224580040295924300187604334099896036246789641632564134246125461"
          "686950415467406032909029192869357953282578032075146446173674602"
          "635247710")
B_Y = int("298819210078481492676017930443930673437544040154080242095928241"
          "372331506189835876003536878655418784733982303233503462500531545"
          "062832660")
KEY_LEN = 57          # b/8, with b = 456
SIG_LEN = 114         # 2b/8
HASH_LEN = 114


def _shake256(data: bytes, length: int = HASH_LEN) -> bytes:
    return hashlib.shake_256(data).digest(length)


def _dom4(phflag: int, context: bytes) -> bytes:
    """RFC 8032 §5.2.1.  Ed448 always prefixes; there is no "pure vs prefixed"
    choice as there is for Ed25519."""
    if len(context) > 255:
        raise ValueError("Ed448 context is limited to 255 bytes")
    return b"SigEd448" + bytes([phflag, len(context)]) + context


def _inv(x: int) -> int:
    return pow(x, P - 2, P)


# ------------------------------------------------------------------- points
# Affine (x, y).  The identity is (0, 1).

def _add(p1, p2):
    x1, y1 = p1
    x2, y2 = p2
    t = D * x1 * x2 % P * y1 % P * y2 % P
    x3 = (x1 * y2 + x2 * y1) % P * _inv(1 + t) % P
    y3 = (y1 * y2 - x1 * x2) % P * _inv(1 - t) % P
    return (x3, y3)


def _mul(point, scalar: int):
    result = (0, 1)
    addend = point
    while scalar:
        if scalar & 1:
            result = _add(result, addend)
        addend = _add(addend, addend)
        scalar >>= 1
    return result


def _encode_point(point) -> bytes:
    x, y = point
    out = bytearray(y.to_bytes(KEY_LEN, "little"))
    out[56] |= (x & 1) << 7          # sign bit in the spare top bit
    return bytes(out)


def _decode_point(data: bytes):
    """Returns None for a non-canonical or off-curve encoding, which callers
    must treat as an invalid signature rather than an exception."""
    if len(data) != KEY_LEN:
        return None
    sign = data[56] >> 7
    y = int.from_bytes(bytes(data[:56]) + bytes([data[56] & 0x7F]), "little")
    if y >= P:
        return None
    # x^2 = (y^2 - 1) / (d y^2 - 1)
    numerator = (y * y - 1) % P
    denominator = (D * y % P * y - 1) % P
    if denominator == 0:
        return None
    x_squared = numerator * _inv(denominator) % P
    if x_squared == 0:
        if sign:
            return None                     # -0 is not a valid encoding
        return (0, y)
    x = pow(x_squared, (P + 1) // 4, P)     # p == 3 (mod 4)
    if x * x % P != x_squared:
        return None                         # not a square: off the curve
    if x & 1 != sign:
        x = (-x) % P
    return (x, y)


# ------------------------------------------------------------------ the API

def _expand(seed: bytes):
    if len(seed) != KEY_LEN:
        raise ValueError("Ed448 seed must be %d bytes" % KEY_LEN)
    digest = bytearray(_shake256(seed))
    clamped = digest[:KEY_LEN]
    clamped[0] &= 0xFC          # clear the two low bits
    clamped[55] |= 0x80         # set the high bit of the second-to-last octet
    clamped[56] = 0x00          # clear the last octet entirely
    scalar = int.from_bytes(bytes(clamped), "little")
    prefix = bytes(digest[KEY_LEN:])
    return scalar, prefix


def public_key(seed: bytes) -> bytes:
    scalar, _prefix = _expand(seed)
    return _encode_point(_mul((B_X, B_Y), scalar))


def sign(seed: bytes, message: bytes, context: bytes = b"") -> bytes:
    scalar, prefix = _expand(seed)
    encoded_a = _encode_point(_mul((B_X, B_Y), scalar))
    dom = _dom4(0, context)
    r = int.from_bytes(_shake256(dom + prefix + message), "little") % L
    encoded_r = _encode_point(_mul((B_X, B_Y), r))
    k = int.from_bytes(
        _shake256(dom + encoded_r + encoded_a + message), "little") % L
    s = (r + k * scalar) % L
    return encoded_r + s.to_bytes(KEY_LEN, "little")


def verify(pub: bytes, message: bytes, signature: bytes,
           context: bytes = b"") -> bool:
    if len(signature) != SIG_LEN or len(pub) != KEY_LEN:
        return False
    point_a = _decode_point(pub)
    point_r = _decode_point(signature[:KEY_LEN])
    if point_a is None or point_r is None:
        return False
    s = int.from_bytes(signature[KEY_LEN:], "little")
    if s >= L:
        return False
    k = int.from_bytes(
        _shake256(_dom4(0, context) + signature[:KEY_LEN] + pub + message),
        "little") % L
    left = _mul((B_X, B_Y), s)
    right = _add(point_r, _mul(point_a, k))
    # Cofactor 4: compare 4*[s]B with 4*(R + [k]A), as RFC 8032 permits.
    for _ in range(2):
        left = _add(left, left)
        right = _add(right, right)
    return left == right


