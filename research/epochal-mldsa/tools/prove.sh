# Runs every piece of evidence for the prototype and writes RESULTS.md.
# Any failure stops the run and leaves no RESULTS.md claiming success.
#
#   tools/prove.sh [--offline-vectors DIR] [out.md]
#
# PYTHON: an interpreter whose `cryptography` has ML-DSA (OpenSSL >= 3.5);
# default python3. EPOCHAL_DEEP_CASES: cases per property in the deep run
# (default 4096).
set -euo pipefail
cd "$(dirname "$0")/.."
PY=${PYTHON:-python3}
VEC_DIR=""
if [ "${1:-}" = "--offline-vectors" ]; then VEC_DIR=$2; shift 2; fi
OUT=${1:-RESULTS.md}
DEEP=${EPOCHAL_DEEP_CASES:-4096}
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT

section() { printf '\n## %s\n\n' "$1" >>"$TMP/r.md"; }
fence() { { echo '```'; cat; echo '```'; } >>"$TMP/r.md"; }
ver() { awk -v n="$1" '$0=="name = \""n"\"" {getline; gsub(/version = |"/,""); print; exit}' Cargo.lock; }

commit=$(git rev-parse --short=12 HEAD 2>/dev/null || echo unknown)
dirty=$(git status --porcelain -- . 2>/dev/null | grep -v '^?? RESULTS.md$' | head -1 || true)
{
  echo "# Results: epochal ML-DSA-87 prototype"
  echo
  echo "Generated by \`tools/prove.sh\` on $(date -u +%F) from commit \`$commit\`$([ -n "$dirty" ] && echo ' plus uncommitted changes')."
  echo "Every number and table below is that run's output. Re-run the script"
  echo "to reproduce it; nothing here is typed in by hand."
} >"$TMP/r.md"

section "Environment"
{
  echo "rustc            $(rustc --version)"
  echo "ml-dsa           $(ver ml-dsa)   (RustCrypto: the prototype's implementation)"
  echo "pqcrypto-mldsa   $(ver pqcrypto-mldsa)   (PQClean: independent verifier)"
  echo "sha3             $(ver sha3)"
  echo "OpenSSL          $($PY -c 'from cryptography.hazmat.backends.openssl.backend import backend as b; print(b.openssl_version_text())')   (third verifier, public data only)"
  echo "Cargo.lock       sha256 $(sha256sum Cargo.lock | cut -c1-16)"
  echo "vectors          sha256 $(sha256sum vectors/acvp-mldsa87.json | cut -c1-16)"
} | fence

section "1. The NIST vectors are NIST's"
if [ -n "$VEC_DIR" ]; then
  $PY vectors/extract_acvp.py "$VEC_DIR" >"$TMP/x.log"
  how="from local copies (each checked against its pinned SHA-256)"
else
  $PY vectors/extract_acvp.py >"$TMP/x.log"
  how="downloaded from ACVP-Server at the pinned commit (each checked against its pinned SHA-256)"
fi
git diff --quiet -- vectors/acvp-mldsa87.json 2>/dev/null || { echo "vectors differ from the committed file" >&2; exit 1; }
{
  echo "\`vectors/extract_acvp.py\` regenerated \`vectors/acvp-mldsa87.json\` $how,"
  echo "and the result is byte-identical to the committed file."
} >>"$TMP/r.md"

section "2. Every test"
cargo test -q --offline --release --no-run 2>/dev/null
cargo test --offline --release -- --test-threads=1 2>&1 | grep -E '^(     Running|   Doc-tests|test |test result)' \
  | sed -E 's/^     Running ([^ ]+).*/\n\1/; s/^   Doc-tests (.*)/\ndoc-tests \1/' | tee "$TMP/t.log" | fence
if grep -q -E 'FAILED|failed; [1-9]' "$TMP/t.log"; then echo "tests failed" >&2; exit 1; fi
total=$(grep -oE 'ok\. [0-9]+ passed' "$TMP/t.log" | awk '{s+=$2} END {print s}')
echo "**$total tests passed, 0 failed.**" >>"$TMP/r.md"

section "3. Properties, deep run"
start=$(date +%s)
EPOCHAL_PROPTEST_CASES=$DEEP cargo test -q --offline --release --test properties 2>&1 | grep 'test result' | fence
echo "$DEEP generated cases per property, fixed generator seed, $(( $(date +%s) - start )) s." >>"$TMP/r.md"

section "4. A third implementation: OpenSSL"
echo "Public data exported by \`proofs::export_public_cases_for_an_outside_verifier\`:" >>"$TMP/r.md"
$PY vectors/verify_openssl.py | fence

section "5. Mutation checks: the tests are not vacuous"
$PY tools/mutants.py >>"$TMP/r.md"

section "6. Cost"
cargo run -q --offline --release --example bench 500 >>"$TMP/r.md"
echo >>"$TMP/r.md"
echo "Medians on the machine that ran this script ($(uname -m))." >>"$TMP/r.md"

cat >>"$TMP/r.md" <<'SCOPE'

## What this run shows, and what it does not

Shown by execution, above:

- **FIPS 204.** Seed-to-key, signing and verification are ML-DSA-87 as NIST
  specifies (section 2, `conformance`; the vectors are NIST's, section 1).
  So a release, 32 bytes, rebuilds the key in any conforming
  implementation, not just this one.
- **C2, exactly.** A forger holding only the release makes, for the same
  randomiser, the holder's signature byte for byte, and rebuilds the
  holder's key byte for byte (`p1_…`). The randomiser is uniform, so
  forgeries and real signatures are identically distributed. That is
  stronger than any statistical test: no test can tell them apart.
- **Three implementations agree.** RustCrypto, PQClean and OpenSSL
  accept the forgeries in the released epoch, and reject them in any other
  (`p2_…`, section 4).
- **C3 over generated cases.** A release forges its own epoch and no
  other, unreleased epochs keep authenticating, and only closed epochs can
  be released (section 3).
- **The written derivation.** The chain, seed, key and binding tag are
  ANALYSIS §2's formulas, recomputed in the test and pinned as known
  answers (`p3_…`).
- **No vacuous gate.** Each rule has a test that fails when the rule is
  broken (section 5).

Not shown, and not claimed:

- **The assumptions.** ML-DSA-87 is EUF-CMA, and SHA3-256 is one-way, so
  that a release reveals nothing of the next epoch. A test cannot show
  either; they are the standard assumptions.
- **No formal proof.** There is no reduction in a formal model. C is
  demonstrated by execution, not proved. That is a cryptographer's job.
- **Erasure in memory.** The mutation shows a released key leaves the
  signer. Zeroisation is the `ml-dsa` and `zeroize` crates', and is not
  observable from safe Rust.
- **Side channels.** Constant time is not tested.
- **The link from `pk_N` to a person** (ANALYSIS §1a). The test
  `limitation_a_long_term_certificate_of_the_epoch_key_stays_evidence`
  shows a long-term certificate re-attributes it. The deniable binding, a
  certificate chain, is not built.
- **Outside the code.** That a release reaches anyone, that a third party
  accepts it, and what a server or device kept.
SCOPE
mv "$TMP/r.md" "$OUT"
echo "wrote $OUT"
